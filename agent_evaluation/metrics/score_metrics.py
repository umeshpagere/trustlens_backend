def evaluate_score(predicted_score, expected_range):
    """
    Evaluates if the predicted credibility score falls within the expected range.
    
    Args:
        predicted_score (float): The score generated by the agent (0-100).
        expected_range (list[int]): [low, high] range from dataset.
        
    Returns:
        dict: {
            "score_correct": bool,
            "score_error_distance": float
        }
    """
    if predicted_score is None or not expected_range or len(expected_range) < 2:
        return {"score_correct": False, "score_error_distance": 100.0}

    low, high = expected_range
    is_correct = low <= predicted_score <= high
    
    distance = 0.0
    if predicted_score < low:
        distance = float(low - predicted_score)
    elif predicted_score > high:
        distance = float(predicted_score - high)

    return {
        "score_correct": is_correct,
        "score_error_distance": distance
    }
